#!/usr/bin/env python3
"""Parse benchmark output into structured JSON, and aggregate across GPUs.

Two modes:

  # 1. parse one run.txt into results/<slug>/timings.json (called by run_benchmark.sh)
  python3 collect_results.py --run results/h100/run.txt --out results/h100/timings.json \
          --gpu "NVIDIA H100" --slug h100 --arch sm_90

  # 2. build a cross-GPU comparison table from every results/*/timings.json
  python3 collect_results.py --table            # prints markdown to stdout
  python3 collect_results.py --table --out results/SUMMARY.md

This is the bridge that lets the package "leave room" for other GPUs: drop a new
results/<slug>/timings.json in (produced automatically by a run on that hardware)
and it shows up in the table and is plottable by gen_plots.py.
"""
import argparse
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.normpath(os.path.join(HERE, "..", "results"))

# a data row: "  100000000   0.0932   0.0938   0.0045   10.4502" (commas allowed in paths)
ROW = re.compile(r"^\s*([\d,]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*$")

# which implementation a section belongs to, keyed by a marker line
MARKERS = [
    ("cuda", "CUDA C benchmark"),
    ("pytorch", "PyTorch GPU baseline"),
    ("mojo", "Mojo GPU kernel"),
]


def parse_run(path):
    """Parse a run.txt into {impl: [(paths,min,med,std,price), ...]}."""
    impl = None
    data = {"cuda": [], "pytorch": [], "mojo": []}
    with open(path) as f:
        for line in f:
            for key, marker in MARKERS:
                if marker in line:
                    impl = key
            m = ROW.match(line)
            if m and impl is not None:
                paths = int(m.group(1).replace(",", ""))
                vals = [float(m.group(i)) for i in (2, 3, 4, 5)]  # min, med, std, price
                data[impl].append((paths,) + tuple(vals))
    return data


def build_timings(run_path, gpu, slug, arch):
    data = parse_run(run_path)
    # path axis from CUDA (all three share it); fall back to whichever is populated
    rows = data["cuda"] or data["mojo"] or data["pytorch"]
    if not rows:
        raise SystemExit(f"no data rows parsed from {run_path}")
    paths = [r[0] for r in rows]

    def series(impl):
        rs = {r[0]: r for r in data[impl]}
        return {
            "min_ms": [rs[p][1] if p in rs else None for p in paths],
            "median_ms": [rs[p][2] if p in rs else None for p in paths],
            "std_ms": [rs[p][3] if p in rs else None for p in paths],
            "price": [rs[p][4] if p in rs else None for p in paths],
        }

    out = {"gpu": gpu, "slug": slug, "arch": arch, "paths": paths,
           "cuda": series("cuda"), "mojo": series("mojo"),
           "pytorch": series("pytorch")}
    return out


def load_all():
    """Load every results/*/timings.json, sorted by slug."""
    out = []
    for p in sorted(glob.glob(os.path.join(RESULTS_DIR, "*", "timings.json"))):
        with open(p) as f:
            out.append(json.load(f))
    return out


def fmt(x):
    return "--" if x is None else f"{x:.4f}"


def make_table(gpus):
    """Markdown table: one block per path count, a row per GPU."""
    if not gpus:
        return "_No results/*/timings.json found yet._\n"
    lines = ["# Cross-GPU summary",
             "",
             "Median per-launch time (ms) at each path count, with Mojo/CUDA parity and",
             "the compiled-kernel speedup over PyTorch. Generated by collect_results.py.",
             ""]
    path_set = sorted({p for g in gpus for p in g["paths"]})
    for n in path_set:
        lines += [f"## {n:,} paths", "",
                  "| GPU | arch | CUDA C | Mojo | PyTorch | Mojo/CUDA | Mojo vs PyTorch |",
                  "|-----|------|-------:|-----:|--------:|----------:|----------------:|"]
        for g in gpus:
            if n not in g["paths"]:
                continue
            i = g["paths"].index(n)
            c = g["cuda"]["median_ms"][i]
            m = g["mojo"]["median_ms"][i]
            p = g["pytorch"]["median_ms"][i]
            ratio = f"{m/c:.2f}x" if (c and m) else "--"
            spd = f"{p/m:.0f}x" if (p and m) else "--"
            lines.append(f"| {g['gpu']} | {g.get('arch','?')} | {fmt(c)} | {fmt(m)} "
                         f"| {fmt(p)} | {ratio} | {spd} |")
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", help="run.txt to parse")
    ap.add_argument("--out", help="output file (timings.json or, with --table, .md)")
    ap.add_argument("--gpu", default="unknown")
    ap.add_argument("--slug", default="gpu")
    ap.add_argument("--arch", default="unknown")
    ap.add_argument("--table", action="store_true",
                    help="aggregate every results/*/timings.json into a markdown table")
    args = ap.parse_args()

    if args.table:
        md = make_table(load_all())
        if args.out:
            with open(args.out, "w") as f:
                f.write(md)
            print(f"wrote {args.out}")
        else:
            print(md)
        return

    if not args.run or not args.out:
        ap.error("parse mode needs --run and --out")
    timings = build_timings(args.run, args.gpu, args.slug, args.arch)
    with open(args.out, "w") as f:
        json.dump(timings, f, indent=2)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
